"""Category: defaults & annotations (definition axes D3/D4).

Varies parameter defaults (immutable, mutable, callable, sentinel, expression,
defaults on keyword-only params) and annotations (simple/complex/forward-ref,
annotated-with-default, return annotations). Signature shape is held to a
canonical plain positional-or-keyword param and the target/source/inferability
axes are held canonical (bare name, editable same-module, fully inferable) so
this file isolates the defaults and annotations axes.

For each default/annotation shape we vary the *call*: omit the defaulted arg
(``arity_defaults_omitted``), pass it positionally, and pass it by keyword --
the three variants a 'prefer keyword' / 'arg name mismatch' rule cares about.
"""

