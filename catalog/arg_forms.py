"""Category: per-argument forms at the call site (call axis C1).

Varies how each argument is expressed: positional literal; positional variable
whose name MATCHES vs MISMATCHES the parameter name; attribute / subscript /
call-result / expression / literal-container as a positional arg; keyword arg;
keyword whose value-variable matches vs mismatches the key; keyword with a
literal value; keyword whose value attribute tail matches the key. Definition
held to a canonical `def function(parameter): ...` (or a small fixed signature)
unless the case is specifically about name matching across several params.

This file is the heart of the motivating talk: argument-name vs parameter-name
matching. `rectangle(width, width)` silently passes the width value for the
height parameter, whereas `rectangle(width, height)` reads correctly.
"""

